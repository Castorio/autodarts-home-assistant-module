"""Cross-language contract: payloads built by the TS mapper must pass PUSH_SCHEMA.

tests/fixtures/push_payloads.json is generated by src/contract.test.ts; see there
for how to regenerate it.
"""

import json
from pathlib import Path

import pytest

from custom_components.io_darts.const import PUSH_TYPES
from custom_components.io_darts.schema import PUSH_SCHEMA

FIXTURE = Path(__file__).parent / "fixtures" / "push_payloads.json"
PAYLOADS = json.loads(FIXTURE.read_text(encoding="utf-8"))


def test_fixture_covers_every_push_type():
    assert {p["type"] for p in PAYLOADS} == PUSH_TYPES


@pytest.mark.parametrize("payload", PAYLOADS, ids=lambda p: p["type"])
def test_mapper_payload_passes_push_schema_unchanged(payload):
    assert PUSH_SCHEMA(payload) == payload
